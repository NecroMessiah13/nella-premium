const THUMBOR = 'https://thumbor.uds.app/unsafe/fit-in/1000x1000/filters:quality(90)';
const PUBLIC_ROOT = path.join(process.cwd(), 'public');
const IMG_DIR_REL = 'products/uds';

async function download(url: string, filePath: string): Promise<boolean> {
  try {
    const res = await fetch(url);
    if (!res.ok) return false;
    const buf = Buffer.from(await res.arrayBuffer());
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, buf);
    return true;
  } catch (e) {
    console.error('  download failed:', url, e);
    return false;
  }
}
const slugify = (s: string) => String(s).replace(/[^a-zA-Z0-9-]+/g, '');

async function main() {
  const catIds = new Map<string, number>();
  for (const c of categories) {
    const rec = await db.category.upsert({ where: { slug: c.slug }, update: { name: c.name }, create: { name: c.name, slug: c.slug } });
    catIds.set(c.slug, rec.id);
    console.log('category ok:', c.name, '(', c.slug, ')');
  }

  let created = 0, updated = 0, failed = 0;
  for (const p of products) {
    const pubDir = path.join(PUBLIC_ROOT, IMG_DIR_REL, p.slug);
    const imgUrls: { url: string; alt: string | null }[] = [];
    let okCount = 0;
    for (let i = 0; i < p.photos.length; i++) {
      const url = `${THUMBOR}/${p.photos[i]}`;
      const filePath = path.join(pubDir, `${i + 1}.jpg`);
      const downloaded = await download(url, filePath);
      if (downloaded) { okCount++; imgUrls.push({ url: `/${IMG_DIR_REL}/${p.slug}/${i + 1}.jpg`, alt: `${p.name} фото ${i + 1}` }); }
    }
    if (imgUrls.length === 0) { console.error('NO IMAGES for', p.name, 'skipped'); failed++; continue; }

    const catId = catIds.get(p.categorySlug)!;
    const existing = await db.product.findUnique({ where: { slug: p.slug } });
    const rec = await db.product.upsert({
      where: { slug: p.slug },
      update: { name: p.name, price: Number(p.price), color: p.color, tone: p.tone, badge: p.badge, categoryId: catId, description: p.description, source: 'UDS', sourceUrl: p.sourceUrl },
      create: { slug: p.slug, name: p.name, price: Number(p.price), color: p.color, tone: p.tone, badge: p.badge, categoryId: catId, description: p.description, source: 'UDS', sourceUrl: p.sourceUrl },
    });

    await db.productImage.deleteMany({ where: { productId: rec.id } });
    for (let i = 0; i < imgUrls.length; i++) await db.productImage.create({ data: { productId: rec.id, url: imgUrls[i].url, alt: imgUrls[i].alt, sortOrder: i } });

    await db.productVariant.deleteMany({ where: { productId: rec.id } });
    if (p.variants.length) {
      const seen = new Set<string>();
      for (const v of p.variants) {
        let sku = `${p.slug}-${slugify(v.size) || 'ns'}`;
        let n = 2; while (seen.has(sku)) { sku = `${p.slug}-${slugify(v.size)}-${n++}`; }
        seen.add(sku);
        await db.productVariant.create({ data: { productId: rec.id, sku, size: v.size, color: p.color, stock: Number(v.inStock ?? 0) } });
      }
    } else {
      for (const size of ['S', 'M', 'L', 'XL']) await db.productVariant.create({ data: { productId: rec.id, sku: `${p.slug}-${size}`, size, color: p.color, stock: 8 } });
    }
    existing ? updated++ : created++;
    console.log(`${existing ? 'updated' : 'created'}: ${p.name} -> ${okCount} imgs cat=${p.category}`);
  }
  console.log(`DONE. created=${created} updated=${updated} failed=${failed}`);
}

main().catch(e => { console.error(e); process.exit(1); }).finally(() => db.$disconnect());
